"""Generate results/concurrency.md -- the numbers the README quotes.

Uses a simulated backend with a fixed service time, not a live API. That is
deliberate: the claim under test is about the *client's* admission control,
and a real endpoint's variance would swamp the effect being measured. The
limitation is stated in the output.

Run:  python scripts/generate_results.py
"""

from __future__ import annotations

import asyncio
import platform
import sys
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))

from llm_client_kit.concurrency import bounded_map  # noqa: E402

OUT = Path(__file__).resolve().parent.parent / "results" / "concurrency.md"

N_TASKS = 128
SERVICE_S = 0.020
LIMITS = (1, 2, 4, 8, 16, 32, 64, 128)
SEED_NOTE = "deterministic: fixed service time, no randomness"


async def measure(limit: int) -> dict[str, float | int]:
    async def work(_: int) -> int:
        await asyncio.sleep(SERVICE_S)
        return 1

    _, stats = await bounded_map(work, range(N_TASKS), limit=limit)
    return stats.summary()


async def main() -> None:
    rows = [(lim, await measure(lim)) for lim in LIMITS]

    L: list[str] = []
    add = L.append
    add("# Concurrency measurements\n")
    add("Generated by `python scripts/generate_results.py`. Do not edit by hand.\n")
    add(f"- Date: {date.today().isoformat()}")
    add(f"- Python: {platform.python_version()} on {platform.system()} "
        f"{platform.machine()}")
    add(f"- Tasks: {N_TASKS}, simulated service time {SERVICE_S * 1000:.0f} ms each")
    add(f"- Seed: {SEED_NOTE}")
    add("- Reproduce: `python scripts/generate_results.py`\n")

    add("## Where the wall-clock goes\n")
    add("| limit | p50 total | p95 total | p95 queued | p95 service | bound by |")
    add("|---|---|---|---|---|---|")
    for lim, s in rows:
        bound = "admission" if s["p95_queued_s"] > s["p95_service_s"] else "service"
        add(f"| {lim} | {s['p50_total_s'] * 1000:.0f} ms | {s['p95_total_s'] * 1000:.0f} ms | "
            f"{s['p95_queued_s'] * 1000:.0f} ms | {s['p95_service_s'] * 1000:.0f} ms | {bound} |")

    tight = rows[0][1]
    loose = rows[-1][1]
    add("")
    add("## What this shows\n")
    add(f"At `limit=1`, p95 total is **{tight['p95_total_s'] * 1000:.0f} ms** of which "
        f"**{tight['p95_queued_s'] * 1000:.0f} ms is queueing** and only "
        f"{tight['p95_service_s'] * 1000:.0f} ms is service. At "
        f"`limit={LIMITS[-1]}` the same work reports "
        f"**{loose['p95_total_s'] * 1000:.0f} ms**.\n")
    add("The service time never changed. It is a property of the work, not of the")
    add("client. Everything else was admission delay — and a single reported")
    add("latency number cannot tell you which of the two you are looking at.\n")
    add("That distinction decides the fix. Admission-bound means raise the limit")
    add("or shed load; service-bound means a faster backend. Acting on the wrong")
    add("one wastes the effort.\n")

    add("## Limitations\n")
    add("- **Simulated backend, not a live endpoint.** The claim under test is")
    add("  about this client's admission control; real API variance would swamp")
    add("  the effect. It does not predict latency against any real provider.")
    add("- Single machine, single event loop. No network, no TLS, no DNS.")
    add("- `asyncio.sleep` is a lower bound on real I/O: no connection pool")
    add("  contention, no head-of-line blocking from HTTP/2 multiplexing.\n")

    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(OUT.parent.parent)} ({len(L)} lines)")


if __name__ == "__main__":
    asyncio.run(main())
