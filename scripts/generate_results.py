"""Generate the concurrency results.

Two outputs, deliberately separated:

- ``results/concurrency.md``      committed. Only *machine-independent* claims:
                                  ratios, which resource bounds the run, and
                                  the invariance of service time. CI regenerates
                                  this and fails if it drifts.
- ``results/concurrency-raw.md``  gitignored. The absolute millisecond timings
                                  from whichever machine ran it.

The split exists because the first version of this script committed raw
timings, and CI failed immediately: `asyncio.sleep(0.020)` overshoots to ~32 ms
on a Windows laptop and lands at ~20 ms on a Linux runner. Byte-comparing
wall-clock numbers across machines is a broken gate.

The fix is not a weaker gate. It is to commit the claims that *are* stable --
"service time does not vary with the concurrency limit", "p95 scales as
ceil(N/limit)" -- and to keep the raw numbers as local evidence. A portable
claim is also a stronger claim.

Run:  python scripts/generate_results.py
"""

from __future__ import annotations

import asyncio
import platform
import sys
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))

from llm_client_kit.concurrency import bounded_map  # noqa: E402

RESULTS = Path(__file__).resolve().parent.parent / "results"
OUT = RESULTS / "concurrency.md"          # invariants only, committed
RAW = RESULTS / "concurrency-raw.md"      # machine-specific, gitignored

N_TASKS = 128
SERVICE_S = 0.020
LIMITS = (1, 2, 4, 8, 16, 32, 64, 128)


async def measure(limit: int) -> dict[str, float | int]:
    async def work(_: int) -> int:
        await asyncio.sleep(SERVICE_S)
        return 1

    _, stats = await bounded_map(work, range(N_TASKS), limit=limit)
    return stats.summary()


def write_invariants(rows: list[tuple[int, dict]]) -> None:
    """Only claims that hold on any machine."""
    by_limit = dict(rows)
    services = [s["p95_service_s"] for _, s in rows]
    spread = (max(services) - min(services)) / max(services)

    # p95 total should track the number of sequential waves, ceil(N/limit).
    ratios = []
    for lim, s in rows:
        waves = -(-N_TASKS // lim)
        ratios.append(s["p95_total_s"] / (waves * min(services)))

    L: list[str] = []
    add = L.append
    add("# Concurrency: what holds on any machine\n")
    add("Generated by `python scripts/generate_results.py`. Do not edit by hand.\n")
    add("Absolute timings live in `results/concurrency-raw.md`, which is")
    add("gitignored: `asyncio.sleep` overshoot is machine-dependent, so")
    add("committing millisecond values makes CI fail on a different runner")
    add("for no useful reason. The claims below are the portable ones.\n")
    add(f"- Tasks: {N_TASKS}, target service time {SERVICE_S * 1000:.0f} ms")
    add(f"- Limits swept: {', '.join(str(x) for x in LIMITS)}")
    add("- Reproduce: `python scripts/generate_results.py`")
    add("- Deterministic: fixed service time, no randomness\n")

    add("## 1. Service time does not depend on the concurrency limit\n")
    # Assert a threshold rather than print the measured percentage. Timing
    # noise moves the second significant digit between runs, and a value that
    # changes every run cannot be committed or diffed. A threshold that the
    # script enforces is also a stronger claim than a number nobody checks.
    assert spread < 0.25, f"service time varied {spread:.1%} across limits -- claim broken"
    add(f"Across a {LIMITS[-1] // LIMITS[0]}x range of concurrency limits,")
    add("measured p95 service time stays within **25%** of its maximum.")
    add("This script asserts it and exits non-zero if the claim breaks.\n")
    add("Service time is a property of the work. The limit cannot change it.")
    add("Everything else a caller observes is admission delay.\n")

    add("## 2. Which resource bounds the run\n")
    add("Reported as order-of-magnitude bands, not raw ratios: the exact value")
    add("carries timing noise and would make this file differ on every run.\n")
    add("| limit | queued vs service | bound by |")
    add("|---|---|---|")
    for lim, s in rows:
        q, sv = s["p95_queued_s"], s["p95_service_s"]
        ratio = q / sv if sv else 0.0
        # Rows where queue and service are within 2x of each other are
        # genuinely ambiguous -- the classification flips between runs. Say so
        # rather than reporting whichever side this run happened to land on.
        if ratio < 0.5:
            band, verdict = "<1x", "service"
        elif ratio < 2:
            band, verdict = "~1x", "**crossover** (flips between runs)"
        elif ratio < 10:
            band, verdict = "2-10x", "admission"
        elif ratio < 50:
            band, verdict = "10-50x", "admission"
        else:
            band, verdict = ">50x", "admission"
        add(f"| {lim} | {band} | {verdict} |")
    add("")
    add("The crossover is the useful number: below it you are waiting for a")
    add("slot, above it you are waiting for the backend. **The two are fixed")
    add("by opposite actions** -- raise the limit and shed load, versus buy a")
    add("faster backend. A single latency figure cannot tell you which.\n")

    add("## 3. p95 tracks the number of sequential waves\n")
    add("With N tasks and limit L, work proceeds in ceil(N/L) waves, so p95")
    add("total should approximate `waves x service`.")
    assert max(ratios) < 2.0, f"p95 exceeded 2x the wave model ({max(ratios):.2f}x)"
    add("Observed p95 stays within **2x** of that model across the whole")
    add("sweep -- asserted here -- confirming the semaphore serialises work")
    add("rather than dropping or duplicating it.\n")

    add("## Limitations\n")
    add("- **Simulated backend, not a live endpoint.** The claim under test is")
    add("  about this client's admission control; real API variance would swamp")
    add("  it. These numbers predict nothing about any real provider.")
    add("- `asyncio.sleep` is a lower bound on real I/O: no connection-pool")
    add("  contention, no TLS, no DNS, no HTTP/2 head-of-line blocking.")
    add("- Single machine, single event loop, single process.\n")

    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")


def write_raw(rows: list[tuple[int, dict]]) -> None:
    """Absolute timings from this machine. Gitignored."""
    L: list[str] = []
    add = L.append
    add("# Concurrency: raw timings (machine-specific, not committed)\n")
    add(f"- Date: {date.today().isoformat()}")
    add(f"- Python {platform.python_version()} on {platform.system()} "
        f"{platform.machine()}")
    add(f"- Tasks: {N_TASKS}, target service {SERVICE_S * 1000:.0f} ms\n")
    add("| limit | p50 total | p95 total | p95 queued | p95 service |")
    add("|---|---|---|---|---|")
    for lim, s in rows:
        add(f"| {lim} | {s['p50_total_s'] * 1000:.0f} ms | "
            f"{s['p95_total_s'] * 1000:.0f} ms | "
            f"{s['p95_queued_s'] * 1000:.0f} ms | "
            f"{s['p95_service_s'] * 1000:.0f} ms |")
    add("")
    RAW.write_text("\n".join(L) + "\n", encoding="utf-8")


async def main() -> None:
    RESULTS.mkdir(exist_ok=True)
    rows = [(lim, await measure(lim)) for lim in LIMITS]
    write_invariants(rows)
    write_raw(rows)
    print(f"wrote {OUT.name} (committed) and {RAW.name} (gitignored)")


if __name__ == "__main__":
    asyncio.run(main())
